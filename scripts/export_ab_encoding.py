#!/usr/bin/env python3
"""Regenerates js/widget/src/generated/ab_encoding.generated.ts from
tools/ab_tables.py's encoding constants (``JS_ENCODING``): the colours and the
opacity that the ``ab_transitions`` / ``ab_steps`` matrices and the
``get_ab_*_table(styled=True)`` Styler draw with (ADR-0017, M1).

Run this (via `make export-ab-encoding`, part of `make build`) after changing
them. `tests/tools/ab_tables_test.py` fails CI if the checked-in generated file
drifts from them.
"""

import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from retentioneering.tools import ab_tables  # noqa: E402

OUTPUT_PATH = (
    REPO_ROOT / "js" / "widget" / "src" / "generated" / "ab_encoding.generated.ts"
)


def render() -> str:
    lines = [
        "// AUTO-GENERATED by scripts/export_ab_encoding.py from",
        "// tools/ab_tables.py's encoding constants — do not edit by hand.",
        "// Regenerate with `make export-ab-encoding` after changing them.",
        "",
    ]
    for name in ab_tables.JS_ENCODING:
        value = getattr(ab_tables, name)
        if isinstance(value, tuple):  # an RGB colour, as CSS rgba() takes it
            value = ", ".join(str(channel) for channel in value)
        lines.append(f"export const {name} = {json.dumps(value)};")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render())
    print(f"Wrote {len(ab_tables.JS_ENCODING)} encoding constants to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
